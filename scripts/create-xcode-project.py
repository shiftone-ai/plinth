objects = {}


def identifier(name):
    return hashlib.sha256(name.encode()).hexdigest()[:24].upper()


def obj(identity, isa, **values):
    key = identifier(identity)
    objects[key] = {"isa": isa, **values}
    return key


def configurations(name, settings):
    configs = []
    for configuration in ["Debug", "Release"]:
        values = dict(settings)
        values["SWIFT_OPTIMIZATION_LEVEL"] = "-Onone" if configuration == "Debug" else "-O"
        values["DEBUG_INFORMATION_FORMAT"] = (
            "dwarf" if configuration == "Debug" else "dwarf-with-dsym"
        )
        values["ONLY_ACTIVE_ARCH"] = "YES" if configuration == "Debug" else "NO"
        if settings.get("CODE_SIGN_ENTITLEMENTS"):
            values["PLINTH_APS_ENVIRONMENT"] = (
                "development" if configuration == "Debug" else "production"
            )
        values["SWIFT_ACTIVE_COMPILATION_CONDITIONS"] = (
            ["DEBUG"] if configuration == "Debug" else []
        )
        configs.append(
            obj(
                name + configuration,
                "XCBuildConfiguration",
                name=configuration,
                buildSettings=values,
            )
        )
    return obj(
        name + "Configurations",
        "XCConfigurationList",
        buildConfigurations=configs,
        defaultConfigurationIsVisible="0",
        defaultConfigurationName="Release",
    )


